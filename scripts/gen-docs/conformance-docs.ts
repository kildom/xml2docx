
import * as fs from 'node:fs';

const conformanceTestFile = 'test/conformance/inputs/autogenerated-docs.doctml';

let testsFromDocs = new Set<string>();

export function registerTest(coverage: string, code: string, data?: any)
{
    let testStr: string;
    if (data) {
        testStr = `\n\n<!--\n${coverage}\nDATA: ${JSON.stringify(data)}\n-->\n\n${code}\n\n`;
    } else {
        testStr = `\n\n<!--\n${coverage}\n-->\n\n${code}\n\n`;
    }
    testsFromDocs.add(testStr);
}

export function writeConformanceTests()
{
    let testFile = '';
    for (let test of testsFromDocs) {
        testFile += test;
    }
    testFile += '<!--\nEND\n-->\n';
    fs.writeFileSync(conformanceTestFile, testFile);
}
